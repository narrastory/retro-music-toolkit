import { mkdir, writeFile } from "node:fs/promises";
import {
  createArrangement,
  importInstrument,
  varyMotif,
  placeAnswers,
  compileScore,
  encodeWav,
} from "../dist/index.js";
await mkdir("examples/instruments", { recursive: true });
const save = (path, value) =>
  writeFile(path, JSON.stringify(value, null, 2) + "\n");
const packageFm = {
  instrument: {
    id: "fm-celestial-lead",
    engine: "fm",
    role: "melody",
    range: [60, 96],
    attack: 0.01,
    release: 0.07,
    description:
      "Original two-operator lead with velocity-dependent brightness and modulation.",
    synthesis: {
      harmonicity: 2,
      modulationIndex: 2.8,
      sustain: 0.6,
      volumeDb: -5,
    },
    velocityResponse: { filterOctaves: 1.5, fmIndexScale: 1 },
    provenance: "Original procedural example; no game samples.",
  },
  assets: [],
};
await save("examples/instruments/fm-celestial-lead.json", packageFm);
const zones = [];
const files = [];
for (const [root, low, high] of [
  [60, 48, 71],
  [72, 72, 96],
]) {
  const sr = 44100,
    f = 440 * 2 ** ((root - 69) / 12),
    period = Math.round(sr / f),
    actual = sr / period,
    frames = period * 64;
  const data = Float32Array.from(
    { length: frames },
    (_, i) =>
      0.45 *
      (Math.sin((2 * Math.PI * i) / period) +
        0.12 * Math.sin((4 * Math.PI * i) / period) +
        0.04 * Math.sin((6 * Math.PI * i) / period)),
  );
  const name = `flute-${root}.wav`,
    id = `original-flute-${root}`;
  await writeFile(`examples/instruments/${name}`, encodeWav([data], sr));
  zones.push({
    lowMidi: low,
    highMidi: high,
    rootMidi: root,
    assetId: id,
    tuningCents: 1200 * Math.log2(actual / f),
    loopStartFrame: 0,
    loopEndFrame: frames,
  });
  files.push({
    id,
    file: name,
    provenance:
      "Original periodic harmonic sample generated by create-v3-examples.mjs.",
  });
}
const packageFlute = {
  instrument: {
    id: "sample-original-flute",
    engine: "sample",
    role: "melody",
    range: [48, 96],
    attack: 0.018,
    release: 0.07,
    description:
      "Original two-zone sustained flute-like samples with measured root tuning.",
    sample: { kind: "zones", zones },
    velocityResponse: { filterOctaves: 1 },
    provenance: "Original toolkit demonstration samples.",
  },
  assets: files,
};
await save("examples/instruments/original-flute-package.json", packageFlute);
const config = {
  title: "Starfall Causeway",
  profile: "genesis-inspired",
  scene: "exploration",
  form: "AABA",
  barsPerSection: 4,
  tempo: 120,
};
await save("examples/arrangement-config.json", config);
const scaffold = createArrangement(config);
await save("examples/v3-empty-scaffold.json", scaffold.score);
await save("examples/v3-empty-scaffold.plan.json", scaffold.plan);
let score = await importInstrument(
  scaffold.score,
  packageFm,
  "examples/instruments",
);
score.seed = 731;
score.export.warmupCycles = 2;
score.tracks[0].instrument = "fm-celestial-lead";
const note = (id, at, pitch, duration, extra = {}) => ({
  id,
  kind: "note",
  at,
  pitch,
  duration,
  gate: 0.8,
  velocity: 0.7,
  ...extra,
});
const melodies = {
  A: [
    ["E5", "G5", "A5", "G5"],
    ["C5", "E5", "G5", "E5"],
    ["D5", "E5", "G5", "A5"],
    ["F5", "E5", "D5", "B4"],
  ],
  B: [
    ["A5", "G5", "E5"],
    ["A5", "C6", "A5"],
    ["F5", "A5", "G5"],
    ["D5", "F5", "B4"],
  ],
};
const chords = {
  A: [
    ["C3", ["C4", "E4", "G4"]],
    ["A2", ["C4", "E4", "A4"]],
    ["F2", ["C4", "F4", "A4"]],
    ["G2", ["B3", "D4", "G4"]],
  ],
  B: [
    ["A2", ["C4", "E4", "A4"]],
    ["F2", ["C4", "F4", "A4"]],
    ["D3", ["D4", "F4", "A4"]],
    ["G2", ["B3", "D4", "G4"]],
  ],
};
for (const letter of ["A", "B"]) {
  const lead = score.tracks[0].patterns[letter].events;
  for (let bar = 0; bar < 4; bar++) {
    const seq = melodies[letter][bar],
      base = bar * 4;
    if (letter === "A") {
      lead.push(
        note(`lead-${letter}-${bar}-0`, base, seq[0], 1, {
          gate: 1,
          expression: {
            pitchBendCents: [
              { offsetBeats: 0, value: -35 },
              { offsetBeats: 0.125, value: 0 },
            ],
          },
        }),
      );
      lead.push(
        note(`lead-${letter}-${bar}-1`, base + 1, seq[1], 1, {
          gate: 1,
          articulation: "legato",
          expression: { portamentoBeats: 0.125 },
        }),
      );
      lead.push(
        note(`lead-${letter}-${bar}-2`, base + 2, seq[2], bar === 3 ? 0.5 : 1, {
          velocity: 0.8,
        }),
      );
      lead.push(
        note(`lead-${letter}-${bar}-3`, base + 3, seq[3], 0.5, { gate: 0.75 }),
      );
    } else {
      lead.push(
        note(`lead-${letter}-${bar}-0`, base, seq[0], 1.5, {
          vibrato: { depthCents: 9, rateHz: 5, delayBeats: 0.5 },
        }),
      );
      lead.push(note(`lead-${letter}-${bar}-1`, base + 2, seq[1], 0.5));
      lead.push(note(`lead-${letter}-${bar}-2`, base + 3, seq[2], 0.5));
    }
    const [root, tones] = chords[letter][bar];
    const bass = score.tracks[1].patterns[letter].events;
    [0, 1.5, 2, 3].forEach((at, i) =>
      bass.push(
        note(`bass-${letter}-${bar}-${i}`, base + at, root, i === 0 ? 1 : 0.5, {
          velocity: i === 0 ? 0.85 : 0.65,
        }),
      ),
    );
    const arp = score.tracks[2].patterns[letter].events;
    [0.5, 1.5, 2.5, 3.5].forEach((at, i) =>
      arp.push(
        note(`arp-${letter}-${bar}-${i}`, base + at, tones[i % 3], 0.25, {
          velocity: 0.45,
          gate: 0.65,
        }),
      ),
    );
    const drum = score.tracks[3].patterns[letter].events;
    for (let i = 0; i < 8; i++)
      drum.push({
        id: `drums-${letter}-${bar}-${i}`,
        kind: "hit",
        at: base + i * 0.5,
        sound:
          i === 0 || i === 4 ? "kick" : i === 2 || i === 6 ? "snare" : "hat",
        velocity: i % 2 ? 0.25 : 0.65,
      });
  }
}
score.tracks[0].send = 0.18;
score.tracks[0].automation = [
  {
    parameter: "brightness",
    points: [
      { at: 0, value: 0.3 },
      { at: 16, value: 0.45 },
      { at: 32, value: 0.25 },
      { at: 48, value: 0.5 },
      { at: 64, value: 0.3 },
    ],
  },
  {
    parameter: "send",
    points: [
      { at: 0, value: 0.12 },
      { at: 32, value: 0.25 },
      { at: 48, value: 0.15 },
      { at: 64, value: 0.12 },
    ],
  },
];
score.tracks[2].pan = -0.2;
score.tracks[2].gainDb = -16;
score.mixer.masterDb = -5;
score.tracks.push({
  id: "answer",
  role: "arp",
  instrument: "fm-epiano",
  gainDb: -15,
  pan: 0.2,
  send: 0.1,
  maxVoices: 1,
  voicePolicy: "cut",
  controls: { brightness: 0.4, pluckiness: 0.7 },
  patterns: {},
  clips: [],
});
await save("examples/v3-base-fm.json", compileScore(score).score);
const variation = {
  trackId: "lead",
  clipId: "melody-section-2",
  newPattern: "A-ending",
  mode: "ending",
  fromBeat: 12,
  replacementEvents: [
    note("new-end-1", 12, "F5", 0.75),
    note("new-end-2", 13, "A5", 1),
    note("new-end-3", 14.5, "G5", 0.5),
    note("new-end-4", 15.25, "B4", 0.5),
  ],
};
await save("examples/v3-variation-config.json", variation);
score = varyMotif(score, variation).score;

const answer = {
  leadTrackId: "lead",
  leadClipId: "melody-section-1",
  answerTrackId: "answer",
  newPattern: "A-response",
  candidates: [
    note("busy", 1, "G4", 0.125),
    note("reply-1", 3.6, "E4", 0.125),
    note("reply-2", 7.6, "G4", 0.125),
  ],
};
await save("examples/v3-answer-config.json", answer);
const answered = placeAnswers(score, answer);
score = answered.score;
await save("examples/v3-answer-report.json", answered.report);
await save("examples/v3-starfall-fm.json", compileScore(score).score);
let sampled = await importInstrument(
  score,
  packageFlute,
  "examples/instruments",
);
sampled.title = "Starfall Causeway — sample arrangement";
sampled.profile = "snes-inspired";
sampled.tempo = 108;
sampled.tracks[0].instrument = "sample-original-flute";
sampled.tracks[1].instrument = "sample-bass";
sampled.tracks[2].instrument = "sample-pluck";
sampled.tracks[4].instrument = "sample-pluck";
await save("examples/v3-starfall-sample.json", compileScore(sampled).score);
console.log(
  "Created scaffold, original multi-zone sample package, expressive FM and sample arrangements.",
);
